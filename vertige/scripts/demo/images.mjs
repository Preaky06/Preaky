/** Nom de fichier du paquet : points de code hexadécimaux joints par « - ». */
export const codepoints = (emoji, keepVs = true) =>
  [...emoji]
    .map((c) => c.codePointAt(0).toString(16).padStart(4, "0"))
    .filter((cp) => keepVs || cp !== "fe0f")
    .join("-");
