// Le wolof s'écrit surtout à l'oral ; l'interface retombe sur le français.
const DICTS = { fr, en, es, pt, it, de, ar, tr, ro, pl, uk, ru, zh, vi };
export const RTL = new Set(["ar"]);
const LOCALES = { zh: "zh-CN", pt: "pt-PT", wo: "fr-FR" };

export function locale(lang) {
  return LOCALES[lang] || (DICTS[lang] ? lang : "fr");
}

export function translator(lang) {
  const dict = DICTS[lang] || fr;
  return (key, vars) => {
    let s = dict[key] ?? fr[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
    return s;
  };
}
