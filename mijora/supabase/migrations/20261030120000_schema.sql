-- Vrai seulement pour un administrateur authentifié. « security definer » : lit le rôle sans dépendre des politiques.
create or replace function public.est_admin() returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.role = 'admin')
$$;
revoke all on function public.est_admin() from public;
grant execute on function public.est_admin() to anon, authenticated;

-- Création automatique du profil à l'inscription
create or replace function public.creer_profil() returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.profiles (id) values (new.id) on conflict do nothing;
  return new;
end $$;
create trigger creer_profil after insert on auth.users for each row execute function public.creer_profil();

create or replace function public.maj_updated_at() returns trigger
language plpgsql set search_path = ''
as $$ begin new.updated_at := now(); return new; end $$;

