create table public.recipes (
  id bigint generated by default as identity primary key,
  title_fr text not null,
  original_title text,
  original_language text references public.locales (code),
  slug text not null check (slug ~ '^[a-z0-9-]+$'),
  introduction text not null,
  origin_history text,
  country_id bigint not null references public.countries (id) on delete restrict,
  region_id bigint references public.regions (id) on delete set null,
  category text not null references public.categories (slug),
  preparation_time integer not null check (preparation_time >= 0),
  cooking_time integer not null default 0 check (cooking_time >= 0),
  rest_time integer not null default 0 check (rest_time >= 0),
  total_time integer generated always as (preparation_time + cooking_time + rest_time) stored,
  difficulty public.difficulte not null,
  estimated_budget public.budget not null,
  servings smallint not null check (servings between 1 and 100),
  storage text,
  reheating text,
  precautions text,
  main_image text,
  image_license text,
  image_credit text,
  status public.statut_editorial not null default 'brouillon',
  is_demo boolean not null default false,
  source_url text check (source_url ~ '^https?://'),
  source_author text,
  editorial_notes text,
  verification_date date,
  verified_by uuid references public.profiles (id) on delete set null,
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  recherche tsvector generated always as (
    setweight(to_tsvector('french', public.sans_accent(title_fr)), 'A') ||
    setweight(to_tsvector('simple', public.sans_accent(coalesce(original_title, ''))), 'A') ||
    setweight(to_tsvector('french', public.sans_accent(introduction)), 'C')
  ) stored,
  unique (country_id, slug),
  -- Une recette publiée doit être vérifiée, sourcée, datée et illustrée par une image autorisée
  constraint recette_publiable check (
    status <> 'publie' or (
      verification_date is not null
      and main_image is not null and image_license is not null
      and (source_url is not null or source_author is not null)
    )
  )
);
