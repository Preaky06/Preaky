create schema if not exists extensions;
create extension if not exists pg_trgm with schema extensions;
create extension if not exists unaccent with schema extensions;
create extension if not exists citext with schema extensions;

-- unaccent n'est pas « immutable » : cette enveloppe permet de l'utiliser dans les index et colonnes générées
create or replace function public.sans_accent(t text) returns text
language sql immutable parallel safe set search_path = ''
as $$ select extensions.unaccent('extensions.unaccent'::regdictionary, coalesce(t, '')) $$;

