create or replace function public.date_publication() returns trigger
language plpgsql set search_path = ''
as $$
begin
  if new.status = 'publie' and new.published_at is null then new.published_at := now(); end if;
  return new;
end $$;
create trigger recipes_date_publication before insert or update of status on public.recipes for each row execute function public.date_publication();

create or replace function public.journal_statut() returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  if tg_op = 'INSERT' or new.status is distinct from old.status then
    insert into public.editorial_events (recipe_id, from_status, to_status, user_id)
    values (new.id, case when tg_op = 'UPDATE' then old.status end, new.status, (select auth.uid()));
  end if;
  return null;
end $$;
create trigger recipes_journal after insert or update of status on public.recipes for each row execute function public.journal_statut();

