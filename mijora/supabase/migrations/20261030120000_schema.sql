-- ---------------------------------------------------------------- recherche
-- Recherche plein texte et filtres principaux ; s'exécute avec les droits de l'appelant (les politiques s'appliquent)
create or replace function public.rechercher_recettes(
  q text default null,
  pays text default null,
  regimes text[] default null,
  temps_max integer default null,
  sans_allergenes text[] default null,
  limite integer default 24,
  decalage integer default 0
) returns setof public.recipes
language sql stable security invoker set search_path = ''
as $$
  select r.*
  from public.recipes r
  join public.countries c on c.id = r.country_id
  where (q is null or q = '' or r.recherche @@ websearch_to_tsquery('french', public.sans_accent(q))
         or public.sans_accent(lower(r.title_fr)) operator(extensions.%) public.sans_accent(lower(q)))
    and (pays is null or c.slug = pays)
    and (temps_max is null or r.total_time <= temps_max)
    and (regimes is null or not exists (
      select 1 from unnest(regimes) s
      where not exists (
        select 1 from public.recipe_diets rd join public.diet_types d on d.id = rd.diet_type_id
        where rd.recipe_id = r.id and d.slug = s and rd.compatibility_status in ('compatible', 'adaptable', 'selon_produits'))))
    and (sans_allergenes is null or not exists (
      select 1 from public.recipe_allergens ra join public.allergens a on a.id = ra.allergen_id
      where ra.recipe_id = r.id and a.slug = any (sans_allergenes) and ra.presence_status in ('contient', 'selon_produit')))
  order by case when q is null or q = '' then 0 else ts_rank(r.recherche, websearch_to_tsquery('french', public.sans_accent(q))) end desc, r.title_fr
  limit least(coalesce(limite, 24), 100) offset greatest(coalesce(decalage, 0), 0)
$$;
